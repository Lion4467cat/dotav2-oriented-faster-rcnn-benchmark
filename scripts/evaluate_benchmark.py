"""Parse MMEngine/MMRotate evaluation metrics and generate a benchmark report."""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from configs.dota_v2_classes import DOTA_V2_CLASSES

_TABLE_ROW_RE = re.compile(
    r"^\|\s*([a-z0-9-]+)\s*\|\s*\d+\s*\|\s*\d+\s*\|\s*([0-9.]+)\s*\|\s*([0-9.]+)\s*\|$"
)
_VAL_SUMMARY_RE = re.compile(r"Epoch\(val\)\s+\[(\d+)\].*?dota/mAP:\s*([0-9.]+)")


def _find_map_key(rec: dict) -> str | None:
    if "dota/mAP" in rec:
        return "dota/mAP"
    for k in rec:
        if k.endswith("/mAP") or k == "mAP":
            return k
    return None


def _parse_log_per_class_aps(work_dir: Path) -> tuple[float, int, dict[str, float]]:
    """Parse MMRotate DOTAMetric PrettyTable rows from MMEngine .log files."""
    log_files = sorted(work_dir.rglob("*.log"))
    best_map = -1.0
    best_epoch = 0
    best_aps: dict[str, float] = {}
    valid_classes = set(DOTA_V2_CLASSES)

    for lf in log_files:
        current_aps: dict[str, float] = {}
        for raw_line in lf.read_text(encoding="utf-8", errors="replace").splitlines():
            line = raw_line.strip()
            row_match = _TABLE_ROW_RE.match(line)
            if row_match:
                cls_name, _recall, ap = row_match.groups()
                if cls_name in valid_classes:
                    current_aps[f"dota/{cls_name}_AP"] = float(ap)
                continue

            val_match = _VAL_SUMMARY_RE.search(line)
            if val_match:
                epoch = int(val_match.group(1))
                m_ap = float(val_match.group(2))
                if m_ap > best_map:
                    best_map = m_ap
                    best_epoch = epoch
                    best_aps = dict(current_aps)
                current_aps.clear()

    return best_map, best_epoch, best_aps


def extract_best_metrics(work_dir: Path) -> dict[str, float]:
    """Find best validation record (mAP + per-class APs) from scalars.json and .log."""
    scalar_files = sorted(work_dir.rglob("scalars.json"))
    best_record: dict[str, float] = {}
    best_map = -1.0

    for sf in scalar_files:
        for line in sf.read_text(encoding="utf-8", errors="replace").splitlines():
            line = line.strip()
            if not line:
                continue
            rec = json.loads(line)
            map_key = _find_map_key(rec)
            if map_key and float(rec[map_key]) > best_map:
                best_map = float(rec[map_key])
                best_record = {
                    k: float(v) for k, v in rec.items() if isinstance(v, (int, float))
                }
                best_record["dota/mAP"] = best_map

    log_map, log_epoch, log_aps = _parse_log_per_class_aps(work_dir)
    if log_aps:
        for k, v in log_aps.items():
            best_record.setdefault(k, v)
    if log_map > best_map:
        best_record["dota/mAP"] = log_map
        best_record["step"] = float(log_epoch)

    if "dota/mAP" not in best_record:
        raise ValueError(f"No mAP records found in {work_dir}")
    return best_record


def load_extended_metrics(work_dir: Path) -> dict[str, object] | None:
    """Load extended OBB metrics JSON generated by compute_extended_metrics.py if present."""
    candidates = sorted(work_dir.rglob("extended_metrics.json"))
    if not candidates:
        return None
    return json.loads(candidates[-1].read_text(encoding="utf-8"))


def _fmt(val: object, digits: int = 4, suffix: str = "") -> str:
    if isinstance(val, (int, float)):
        return f"{val:.{digits}f}{suffix}"
    return "—"


def render_markdown_report(
    baseline: dict[str, float] | None,
    flagship: dict[str, float] | None,
    baseline_ext: dict[str, object] | None = None,
    flagship_ext: dict[str, object] | None = None,
) -> str:
    """Format a Markdown comparison report for DOTA v2.0 OBB metrics and diagnostics."""
    lines = [
        "# DOTA v2.0 Benchmark Report (`val` split, OBB `le90`)",
        "",
        "## Core Metrics vs Target Reference",
        "",
        "| Model / Reference | Precision (F1-opt) | Recall (F1-opt) | F1-score | mAP50 | mAP50-95 | AP75 | Best Step |",
        "| :--- | :---: | :---: | :---: | :---: | :---: | :---: | :---: |",
        "| Reference Target (User Provided) | `0.7430` | `0.5670` | `0.6432` | `0.5970` | `0.4210` | — | — |",
    ]

    def _track_row(label: str, base: dict[str, float], ext: dict[str, object] | None) -> str:
        step = int(base.get("step", 0))
        m50 = ext["map50"] if ext else base["dota/mAP"]
        m5095 = ext.get("map50_95") if ext else None
        ap75 = ext.get("ap75") if ext else None
        f1o = ext.get("micro_prf", {}).get("f1_optimal", {}) if ext else {}
        return (
            f"| {label} | {_fmt(f1o.get('precision'))} | {_fmt(f1o.get('recall'))} | "
            f"{_fmt(f1o.get('f1'))} | **{_fmt(m50)}** | {_fmt(m5095)} | {_fmt(ap75)} | {step} |"
        )

    if baseline:
        lines.append(_track_row("Track A: Rotated Faster R-CNN (R50-FPN, 1x)", baseline, baseline_ext))
    if flagship:
        lines.append(
            _track_row("Track B: Oriented Faster R-CNN (ConvNeXt-S + PAFPN + KLD, 2x)", flagship, flagship_ext)
        )
    if baseline and flagship:
        a_m50 = float(baseline_ext["map50"]) if baseline_ext else baseline["dota/mAP"]
        b_m50 = float(flagship_ext["map50"]) if flagship_ext else flagship["dota/mAP"]
        delta_m50 = b_m50 - a_m50
        lines.append(f"| **Delta (Track B - Track A)** | — | — | — | **`{delta_m50:+.4f}`** | — | — | — |")

    if baseline_ext or flagship_ext:
        lines.extend(
            [
                "",
                "## OBB-Specific Diagnostic & Operational Metrics",
                "",
                "| Metric | Track A (Baseline) | Track B (Flagship) |",
                "| :--- | :---: | :---: |",
            ]
        )

        def _g(ext: dict[str, object] | None, *keys: str) -> object:
            cur: object = ext
            for k in keys:
                if not isinstance(cur, dict) or k not in cur:
                    return None
                cur = cur[k]
            return cur

        diag_rows = [
            ("F1-Optimal Conf Threshold", ("micro_prf", "f1_optimal", "conf_threshold"), 4, ""),
            ("Macro Precision (18-class mean)", ("macro_f1_opt", "precision"), 4, ""),
            ("Macro Recall (18-class mean)", ("macro_f1_opt", "recall"), 4, ""),
            ("Precision @ conf=0.30", ("micro_prf", "at_conf", "0.30", "precision"), 4, ""),
            ("Recall @ conf=0.30", ("micro_prf", "at_conf", "0.30", "recall"), 4, ""),
            ("Precision @ conf=0.50", ("micro_prf", "at_conf", "0.50", "precision"), 4, ""),
            ("Recall @ conf=0.50", ("micro_prf", "at_conf", "0.50", "recall"), 4, ""),
            ("Scale AP50: Small (< 32^2 px^2)", ("scale_ap50", "small", "ap50"), 4, ""),
            ("Scale AP50: Medium (32^2..96^2)", ("scale_ap50", "medium", "ap50"), 4, ""),
            ("Scale AP50: Large (> 96^2 px^2)", ("scale_ap50", "large", "ap50"), 4, ""),
            ("Class-Agnostic Localization AP50", ("class_agnostic_ap50",), 4, ""),
            ("Classification Confusion Gap", ("classification_gap_ap50",), 4, ""),
            ("Mean Angle Error - All TPs", ("orientation_error_deg", "mean_all_tp"), 2, " deg"),
            ("Mean Angle Error - Elongated (AR>=1.5)", ("orientation_error_deg", "mean_elongated_tp"), 2, " deg"),
            ("Easy GT Recall (difficult=0)", ("difficulty_recall", "easy_recall"), 4, ""),
            ("Difficult GT Recall (difficult=1)", ("difficulty_recall", "difficult_recall"), 4, ""),
            ("Validation Throughput", ("operational", "fps"), 2, " img/s"),
            ("Model Parameters", ("operational", "params_m"), 2, " M"),
            ("Peak GPU Memory", ("operational", "peak_vram_gb"), 2, " GiB"),
        ]
        for label, path, digits, suffix in diag_rows:
            a_v = _fmt(_g(baseline_ext, *path), digits=digits, suffix=suffix)
            b_v = _fmt(_g(flagship_ext, *path), digits=digits, suffix=suffix)
            lines.append(f"| {label} | {a_v} | {b_v} |")

    lines.extend(["", "## Per-Class AP@0.5 Breakdown", ""])
    lines.append("| Class | Track A AP50 | Track B AP50 | Delta AP50 | Track A AP50-95 | Track B AP50-95 |")
    lines.append("| :--- | :---: | :---: | :---: | :---: | :---: |")

    for cls_name in DOTA_V2_CLASSES:
        key = f"dota/{cls_name}_AP"
        a_val = (
            baseline_ext["per_class"][cls_name]["ap50"]
            if (baseline_ext and cls_name in baseline_ext.get("per_class", {}))
            else (baseline.get(key) if baseline else None)
        )
        b_val = (
            flagship_ext["per_class"][cls_name]["ap50"]
            if (flagship_ext and cls_name in flagship_ext.get("per_class", {}))
            else (flagship.get(key) if flagship else None)
        )
        a_95 = (
            baseline_ext["per_class"][cls_name]["ap50_95"]
            if (baseline_ext and cls_name in baseline_ext.get("per_class", {}))
            else None
        )
        b_95 = (
            flagship_ext["per_class"][cls_name]["ap50_95"]
            if (flagship_ext and cls_name in flagship_ext.get("per_class", {}))
            else None
        )
        a_str = f"{float(a_val):.4f}" if a_val is not None else "—"
        b_str = f"{float(b_val):.4f}" if b_val is not None else "—"
        d_str = (
            f"{(float(b_val) - float(a_val)):+.4f}"
            if (a_val is not None and b_val is not None)
            else "—"
        )
        lines.append(f"| `{cls_name}` | {a_str} | {b_str} | {d_str} | {_fmt(a_95)} | {_fmt(b_95)} |")

    lines.append("")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate DOTA v2.0 benchmark Markdown report.")
    parser.add_argument("--baseline-dir", type=Path, default=None)
    parser.add_argument("--flagship-dir", type=Path, default=None)
    parser.add_argument(
        "--out",
        type=Path,
        default=Path("benchmark_report.md"),
    )
    args = parser.parse_args()

    baseline = extract_best_metrics(args.baseline_dir) if args.baseline_dir else None
    flagship = extract_best_metrics(args.flagship_dir) if args.flagship_dir else None
    baseline_ext = load_extended_metrics(args.baseline_dir) if args.baseline_dir else None
    flagship_ext = load_extended_metrics(args.flagship_dir) if args.flagship_dir else None

    if baseline is None and flagship is None:
        raise ValueError("Provide at least one of --baseline-dir or --flagship-dir")

    report = render_markdown_report(
        baseline,
        flagship,
        baseline_ext=baseline_ext,
        flagship_ext=flagship_ext,
    )
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(report, encoding="utf-8")
    print(report)
    print(f"[report] Saved to {args.out}")


if __name__ == "__main__":
    main()
